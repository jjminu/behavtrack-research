"""Arena and zone definitions, stored in the experiment config."""

from __future__ import annotations

from dataclasses import dataclass, field

from .geometry import Calibration, Shape


@dataclass
class Zone:
    name: str
    shape: Shape
    auto: bool = False  # generated by a paradigm template rather than drawn by hand

    def to_dict(self) -> dict:
        d = {"name": self.name, "shape": self.shape.to_dict()}
        if self.auto:
            d["auto"] = True
        return d

    @classmethod
    def from_dict(cls, d: dict) -> "Zone":
        return cls(d["name"], Shape.from_dict(d["shape"]), bool(d.get("auto", False)))


@dataclass
class Arena:
    name: str
    shape: Shape
    calibration: Calibration = field(default_factory=Calibration)
    zones: list[Zone] = field(default_factory=list)

    def zone(self, name: str) -> Zone | None:
        return next((z for z in self.zones if z.name == name), None)

    def zones_with_prefix(self, prefix: str) -> list[Zone]:
        return [z for z in self.zones if z.name.startswith(prefix)]

    def to_dict(self) -> dict:
        return {
            "name": self.name,
            "shape": self.shape.to_dict(),
            "calibration": self.calibration.to_dict(),
            "zones": [z.to_dict() for z in self.zones],
        }

    @classmethod
    def from_dict(cls, d: dict) -> "Arena":
        return cls(
            d["name"],
            Shape.from_dict(d["shape"]),
            Calibration.from_dict(d.get("calibration")),
            [Zone.from_dict(z) for z in d.get("zones", [])],
        )
